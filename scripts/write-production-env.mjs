#!/usr/bin/env node
/**
 * Write production client env files for website build and admin Angular config.
 *
 * Required env:
 *   PUBLIC_SUPABASE_URL (or SUPABASE_URL)
 *   PUBLIC_SUPABASE_ANON_KEY (or SUPABASE_ANON_KEY)
 *   PUBLIC_SITE_URL
 *   IMPORT_CRON_SECRET
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDirectory = join(dirname(fileURLToPath(import.meta.url)), '..');

function requireEnv(primaryName, fallbackName) {
  const value = process.env[primaryName]?.trim() || process.env[fallbackName]?.trim();
  if (!value) {
    console.error(`[write-production-env] Missing ${primaryName} (or ${fallbackName})`);
    process.exit(1);
  }
  return value;
}

function optionalEnv(name) {
  return process.env[name]?.trim() || '';
}

const supabaseUrl = requireEnv('PUBLIC_SUPABASE_URL', 'SUPABASE_URL');
const supabaseAnonKey = requireEnv('PUBLIC_SUPABASE_ANON_KEY', 'SUPABASE_ANON_KEY');
const siteUrl = requireEnv('PUBLIC_SITE_URL', 'WEBSITE_ORIGIN');
const importCronSecret = requireEnv('IMPORT_CRON_SECRET');
const stripePublishableKey = optionalEnv('PUBLIC_STRIPE_PUBLISHABLE_KEY');

const websiteEnvPath = join(rootDirectory, 'apps/website/.env.production');
const websiteEnv = [
  `PUBLIC_SITE_URL=${siteUrl}`,
  `PUBLIC_SUPABASE_URL=${supabaseUrl}`,
  `PUBLIC_SUPABASE_ANON_KEY=${supabaseAnonKey}`,
  stripePublishableKey ? `PUBLIC_STRIPE_PUBLISHABLE_KEY=${stripePublishableKey}` : null,
]
  .filter(Boolean)
  .join('\n')
  .concat('\n');

writeFileSync(websiteEnvPath, websiteEnv, 'utf8');
console.log(`[write-production-env] Wrote ${websiteEnvPath}`);

const adminEnvDirectory = join(rootDirectory, 'apps/admin/src/environments');
mkdirSync(adminEnvDirectory, { recursive: true });

const adminGeneratedPath = join(adminEnvDirectory, 'production.generated.ts');
const adminGenerated = `/** Generated by scripts/write-production-env.mjs — do not edit. */
export const productionGeneratedConfig = {
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  importCronSecret: ${JSON.stringify(importCronSecret)},
} as const;
`;

writeFileSync(adminGeneratedPath, adminGenerated, 'utf8');
console.log(`[write-production-env] Wrote ${adminGeneratedPath}`);
